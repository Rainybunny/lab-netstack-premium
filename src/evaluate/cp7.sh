#!/bin/bash
set -eu

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
source "$SCRIPT_DIR/lab3lib.sh"

CP=cp7
TRANSCRIPT=$OUT/cp7.txt
: > "$TRANSCRIPT"

N1=${PREFIX}7n1
N2=${PREFIX}7n2
V12=${PREFIX}7v12
V21=${PREFIX}7v21
SERVER_PID=
CAP_PID=

cleanup() {
    [ -n "$SERVER_PID" ] && kill "$SERVER_PID" 2>/dev/null || true
    [ -n "$CAP_PID" ] && kill "$CAP_PID" 2>/dev/null || true
    del_ns "$N1" "$N2"
}
trap cleanup EXIT

say "=== CP7: capture a TCP packet generated by the user-space stack ==="
say "topology: $N1 --- $N2 (10.110.7.0/24)"
say "commands:"
say "  ns2: echo_server"
say "  ns1: echo_client 10.110.7.2"
say "  capture: AF_PACKET on $V12"
say ""

make_ns "$N1" "$N2"
ip link add "$V12" type veth peer name "$V21"
ip link set "$V12" netns "$N1"
ip link set "$V21" netns "$N2"
ip netns exec "$N1" ip addr add 10.110.7.1/24 dev "$V12"
ip netns exec "$N2" ip addr add 10.110.7.2/24 dev "$V21"
isolate "$N1" "$N2"
ip netns exec "$N1" ip link set "$V12" up
ip netns exec "$N2" ip link set "$V21" up

CAP_PID=$(start_capture "$N1" "$V12" "$OUT/cp7.pcap" 120)
sleep 1
ip netns exec "$N2" stdbuf -oL -eL "$BIN/echo_server" \
    > "$OUT/cp7-server.log" 2>&1 &
SERVER_PID=$!
sleep 2
timeout 120 ip netns exec "$N1" stdbuf -oL -eL "$BIN/echo_client" 10.110.7.2 \
    > "$OUT/cp7-client.log" 2>&1 || say "client exit $?"
sleep 2

say "=== echo client output (LINKSTATE control-plane lines removed) ==="
grep -v '^LINKSTATE' "$OUT/cp7-client.log" | tee -a "$TRANSCRIPT" || true
say ""
say "=== echo server output (LINKSTATE control-plane lines removed) ==="
grep -v '^LINKSTATE' "$OUT/cp7-server.log" | tee -a "$TRANSCRIPT" || true
say ""
say "=== TCP header of the first client data segment ==="
python3 -I "$SCRIPT_DIR/tcp_header.py" "$OUT/cp7.pcap" 10086 | tee -a "$TRANSCRIPT"
say ""
say "=== TCP segment summary ==="
python3 -I "$SCRIPT_DIR/retrans.py" "$OUT/cp7.pcap" | tee -a "$TRANSCRIPT"
